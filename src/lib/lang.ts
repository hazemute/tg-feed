/**
 * Лёгкий детектор языка текста поста (без внешних зависимостей и без LLM).
 *
 * Зачем: фильтр ленты «Русский / Другие языки» (запрос владельца). Вызывается
 * на этапе построения индекса ленты (text уже в памяти) — стоимость O(длина),
 * секунда на сотни постов. Персистентность не нужна: язык вычисляется на лету
 * при каждой (редкой) пересборке индекса.
 *
 * Правила:
 *  - 'ru'      — кириллица даёт заметную долю букв. Это «русский сегмент»
 *                ленты: украинский/белорусский и смешанные посты (код +
 *                русский текст) тоже попадают сюда — фильтр языковой, а не
 *                страновой, и резать смешанные посты было бы вредно.
 *  - 'foreign' — буквы есть, кириллицы почти нет (латиница, греческий,
 *                арабский, CJK и т.д.).
 *  - 'und'     — букв нет вовсе (мем-картинки, «🔥🔥», цифры, ссылки).
 *                Такие посты фильтр НЕ прячет ни в одном режиме: иначе
 *                «Русский» вычистил бы всю медиа-ленту.
 */
export type PostLang = 'ru' | 'foreign' | 'und'

/** Режим фильтра ленты (клиентский параметр ?lang=) */
export type LangFilter = 'any' | 'ru' | 'foreign'

/** Проходит ли пост с языком lang под фильтр f */
export function langPasses(lang: PostLang, f: LangFilter): boolean {
  if (f === 'ru') return lang === 'ru' || lang === 'und'
  if (f === 'foreign') return lang === 'foreign' || lang === 'und'
  return true
}

export function detectLang(text: string): PostLang {
  if (!text) return 'und'
  let cyr = 0
  let letters = 0
  for (let i = 0; i < text.length; ) {
    const code = text.codePointAt(i) ?? 0
    i += code > 0xffff ? 2 : 1
    // Кириллица (основной блок + расширенный: ЂЋ ІЇЄҐ, старая кириллица)
    if ((code >= 0x0400 && code <= 0x04ff) || (code >= 0x0500 && code <= 0x052f)) {
      cyr++
      letters++
      continue
    }
    // Латиница: базовая + расширения A/B (умлауты, ł, ç, ѓ-подобные кавычки не трогаем)
    if (
      (code >= 0x0041 && code <= 0x005a) ||
      (code >= 0x0061 && code <= 0x007a) ||
      (code >= 0x00c0 && code <= 0x024f)
    ) {
      letters++
      continue
    }
    // Прочие письменности — считаем буквами, чтобы «foreign» ловил не только EN
    if (
      (code >= 0x0370 && code <= 0x03ff) || // греческий
      (code >= 0x0590 && code <= 0x05ff) || // иврит
      (code >= 0x0600 && code <= 0x06ff) || // арабский
      (code >= 0x0900 && code <= 0x097f) || // деванагари
      (code >= 0x3040 && code <= 0x30ff) || // кана
      (code >= 0x4e00 && code <= 0x9fff) || // CJK
      (code >= 0xac00 && code <= 0xd7af) // хангыль
    ) {
      letters++
    }
  }
  if (letters === 0) return 'und'
  return cyr / letters >= 0.3 ? 'ru' : 'foreign'
}
