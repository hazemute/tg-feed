import { chatMessages } from '@/lib/openrouter'

/**
 * Нейросотрудник поддержки Tg Swipe.
 *
 * Модель — самая дешёвая в цепочке OpenRouter. ЭКОНОМИЯ ТОКЕНОВ (задача
 * «тратилось прям очень мало»): системный промпт сжат в ~2.5 раза (вся
 * knowledge base сохранена, убрана вода), история 8 сообщений × 280 симв.,
 * max_tokens 320 — ответы и так 2-5 предложений. Итог: ~500-700 входящих
 * токенов на сообщение вместо ~2000+.
 *
 * Правила работы:
 *  - знает устройство приложения (промпт ниже — единый источник знаний);
 *  - отвечает в формате markdown (рендерится RichText'ом как посты);
 *  - вопрос, который бот не должен решать сам (деньги, жалобы, реклама,
 *    удаление данных, «позовите человека») → маркер [ESCALATE]: обращение
 *    передаётся сотруднику в админ-панель, диалог продолжается там.
 */

export const SUPPORT_SYSTEM_PROMPT = `Ты — сотрудник поддержки мини-аппа Tg Swipe: умная лента постов из открытых Telegram-каналов. Вход по Telegram одним тапом, есть гостевой режим.

# Устройство (единый источник знаний — не выдумывай ничего сверх)
- Лента собирается автоматически из публичных каналов (t.me + Bot API), круглосуточно. Обновляется сама: потяни ленту вниз — свежие посты поднимутся пилюлей «N новых». Кнопки «обновить» нет.
- Порядок: свежесть + вовлечённость + интересы (темы из профиля). Просмотры/реакции — реальные, из Telegram.
- Тулбар: поиск по постам; фильтры «Медиа», «24ч», «Топ». Категории листаются вкладками.
- «Не интересно» (глаз) скрывает пост; вернуть скрытые — в тулбаре.
- Пост: лайк ♥, закладка (смотреть в профиле), подписка [+] (открывает канал в TG, видна в профиле), полный текст по тапу + «Копировать текст», «Краткое содержание» (AI, 3 пункта), перевод, озвучка «Слушать» (до ~3 мин). Картинки свайпаются, спойлеры — тап.
- «Тренды»: пульс суток, топ постов, хэштеги, каналы. «Поиск»: посты + каталог каналов.
- Профиль: интересы, тема, шрифт, язык, сохранённое, подписки.
- «Мой канал» (авторы): привязка своего канала (бот @tgswipe_bot в админы → авто-подтверждение), тизер-режимы (полностью/обрезка/блюр), статистика, реклама (CPA, оплата за переходы).

# Честные ограничения
Контент из открытых каналов как есть (не редактируем; мусор фильтруется, но сообщи если проскочило). Подписчики/аватарки подтягиваются часами. Озвучка/перевод автоматические. Приложение бесплатно; платит только рекламодатель.

# Стиль ответа
Язык = язык пользователя (по умолчанию русский). Коротко и по-человечески, 2-5 предложений, без канцелярита. Markdown: **жирный**, \`код\`, списки «- ». Без заголовков и таблиц. Не знаешь — так скажи. Никогда не проси пароли/платёжные данные.

# Эскалация к живому сотруднику
Начни ответ ровно с [ESCALATE] (первая строка), если: просят человека/оператора; жалобы на контент, угрозы, юр.вопросы; деньги/оплата/возврат/продвижение; удаление аккаунта/данных; необъяснимый баг (после одного уточнения); вне знаний об приложении. После маркера — одна фраза, что вопрос у сотрудника и ответ придёт в этот чат.`

export const ESCALATE_MARKER = '[ESCALATE]'

/** Ответ при недоступности нейросети — не эскалация, просто извинение. */
export const AI_FALLBACK_REPLY =
  'Не получилось обработать сообщение — техническая заминка на нашей стороне. Напиши ещё раз через минуту, вопрос не потеряется.'

type HistoryItem = { sender: string; text: string }

function roleOf(sender: string): 'user' | 'assistant' {
  return sender === 'user' ? 'user' : 'assistant'
}

/**
 * Диалог с нейросетью поддержки. Возвращает ответ ИИ без маркера и флаг
 * эскалации. Бросает исключение, если ни одна модель не ответила.
 */
export async function supportAiReply(
  history: HistoryItem[],
  userLanguage?: string | null,
): Promise<{ text: string; escalate: boolean }> {
  const messages: Array<{ role: 'system' | 'user' | 'assistant'; content: string }> = [
    { role: 'system', content: SUPPORT_SYSTEM_PROMPT },
  ]
  if (userLanguage && userLanguage.toLowerCase().startsWith('en')) {
    messages.push({
      role: 'system',
      content: 'Пользователь общается на английском — отвечай на английском.',
    })
  }
  // Последние 8 сообщений по 280 символов хватает для контекста: длинные
  // цитаты в поддержку не пересылают, а каждый лишний токен — деньги
  for (const h of history.slice(-8)) {
    messages.push({ role: roleOf(h.sender), content: h.text.slice(0, 280) })
  }

  const raw = await chatMessages(messages, { maxTokens: 320, timeoutMs: 25_000, temperature: 0.3 })
  // Маркер мог прийти в начале или отдельной строкой — вычищаем его
  const escalate = raw.includes(ESCALATE_MARKER)
  const text = (escalate ? raw.replaceAll(ESCALATE_MARKER, '').trim() : raw) || AI_FALLBACK_REPLY
  return { text, escalate }
}
