export const ESCALATE_MARKER = '[ESCALATE]'

/** Ответ при недоступности нейросети — не эскалация, просто извинение. */
export const AI_FALLBACK_REPLY =
  'Не получилось обработать сообщение — техническая заминка на нашей стороне. Напиши ещё раз через минуту, вопрос не потеряется.'

type HistoryItem = { sender: string; text: string }

function roleOf(sender: string): 'user' | 'assistant' {
  return sender === 'user' ? 'user' : 'assistant'
}

/**
 * Диалог с нейросетью поддержки. Возвращает ответ ИИ без маркера и флаг
 * эскалации. Бросает исключение, если ни одна модель не ответила.
 */
export async function supportAiReply(
  history: HistoryItem[],
  userLanguage?: string | null,
): Promise<{ text: string; escalate: boolean }> {
  const messages: Array<{ role: 'system' | 'user' | 'assistant'; content: string }> = [
    { role: 'system', content: SUPPORT_SYSTEM_PROMPT },
  ]
  if (userLanguage && userLanguage.toLowerCase().startsWith('en')) {
    messages.push({
      role: 'system',
      content: 'Пользователь общается на английском — отвечай на английском.',
    })
  }
  // Последние 8 сообщений по 280 символов хватает для контекста: длинные
  // цитаты в поддержку не пересылают, а каждый лишний токен — деньги
  for (const h of history.slice(-8)) {
    messages.push({ role: roleOf(h.sender), content: h.text.slice(0, 280) })
  }

  const raw = await chatMessages(messages, { maxTokens: 320, timeoutMs: 25_000, temperature: 0.3 })
  // Маркер мог прийти в начале или отдельной строкой — вычищаем его
  const escalate = raw.includes(ESCALATE_MARKER)
  const text = (escalate ? raw.replaceAll(ESCALATE_MARKER, '').trim() : raw) || AI_FALLBACK_REPLY
  return { text, escalate }
}
