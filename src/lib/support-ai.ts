/** Промпт поддержки: ядро + живая база знаний (тарифы/курс/розыгрыши/статистика) */
export async function supportSystemPrompt(): Promise<string> {
  const kb = await knowledgeBlock('full').catch(() => '')
  return SUPPORT_CORE_PROMPT.replace('{{KNOWLEDGE}}', kb || '(база знаний временно недоступна — отвечай только по разделу «Устройство»)')
}

/** Совместимость: статическое ядро без знаний (для тестов/логов) */
export const SUPPORT_SYSTEM_PROMPT = SUPPORT_CORE_PROMPT.replace('{{KNOWLEDGE}}', '[живая база знаний подключается в рантайме — supportSystemPrompt()]')

export const ESCALATE_MARKER = '[ESCALATE]'

/** Ответ при недоступности нейросети — не эскалация, просто извинение. */
export const AI_FALLBACK_REPLY =
  'Не получилось обработать сообщение — техническая заминка на нашей стороне. Напиши ещё раз через минуту, вопрос не потеряется.'

type HistoryItem = { sender: string; text: string }

function roleOf(sender: string): 'user' | 'assistant' {
  return sender === 'user' ? 'user' : 'assistant'
}

/**
 * Диалог с нейросетью поддержки. Возвращает ответ ИИ без маркера и флаг
 * эскалации. Бросает исключение, если ни одна модель не ответила.
 */
export async function supportAiReply(
  history: HistoryItem[],
  userLanguage?: string | null,
): Promise<{ text: string; escalate: boolean }> {
  const messages: Array<{ role: 'system' | 'user' | 'assistant'; content: string }> = [
    { role: 'system', content: await supportSystemPrompt() },
  ]
  if (userLanguage && userLanguage.toLowerCase().startsWith('en')) {
    messages.push({
      role: 'system',
      content: 'Пользователь общается на английском — отвечай на английском.',
    })
  }
  // Последние 6 сообщений по 240 символов хватает для контекста: каждый
  // лишний токен — и деньги, и задержка (время ответа растёт с длиной промпта)
  for (const h of history.slice(-6)) {
    messages.push({ role: roleOf(h.sender), content: h.text.slice(0, 240) })
  }

  /* v5.96 СКОРОСТЬ (приказ владельца «ускорь её ответ»): timeout 12с вместо 25с —
   * тормозной/зависший слот быстрее отваливается, цепочка берёт следующую модель;
   * temperature 0.5 — живее тон; maxTokens 260 — ответы и так 1-4 предложения.
   *
   * v5.97 (задача 2-c, «в поддержке он вообще не работает»): диагноз и лечение.
   *  ДИАГНОЗ (замеры .qa/ai-speed.ts + тест POST /api/support): локально через
   *  транспорт z-ai-web-dev-sdk поддержка отвечает за ~1.1с — маршрут и промпт
   *  (6.6КБ ≈ 2К токенов, база знаний не раздута) ЗДОРОВЫ. Ломалось на пути
   *  OpenRouter (прод): мёртвый слот glm-5.3-flash:free первым в цепочке (404)
   *  + перебор 429-слотов подряд → цепочка рвалась/тянулась до фолбэка.
   *  ЛЕЧЕНИЕ: 1) цепочка пересобрана (мёртвые убраны, быстрые первыми);
   *  2) ГОНКА: первые 2 живые модели отвечают параллельно, выигрывает первая
   *  полноценная — ускорение 2-3× на холодном пути; 3) таймаут 11с. */
  const raw = await chatMessagesRace(messages, { maxTokens: 260, timeoutMs: 11_000, temperature: 0.5 })
  // Маркер мог прийти в начале или отдельной строкой — вычищаем его
  const escalate = raw.includes(ESCALATE_MARKER)
  const text = (escalate ? raw.replaceAll(ESCALATE_MARKER, '').trim() : raw) || AI_FALLBACK_REPLY
  return { text, escalate }
}
