-- ПЛЕЙСХОЛДЕРЫ (замените перед запуском):
--   <PROJECT_REF>  — ref проекта Supabase (Settings → General → Reference ID,
--                    выглядит как 'abcdefghijklmnop' — часть хоста
--                    <PROJECT_REF>.supabase.co). Ниже используется в
--                    комментариях/проверках; сам таргет запроса — ДОМЕН
--                    ПРИЛОЖЕНИЯ, а не Supabase.
--   <APP_DOMAIN>   — домен деплоя Next.js на Vercel, например
--                    'tg-feed-<PROJECT_REF>.vercel.app' или кастомный домен
--                    (URL НЕ должен заканчиваться слэшем).
--   <CRON_SECRET>  — значение переменной CRON_SECRET из Vercel env (то же,
--                    что в .env приложения).
--
-- КАК ЗАПУСКАТЬ: Supabase Dashboard → SQL Editor. Раскомментируйте блоки
-- после замены плейсхолдеров. Секция «Расписание» закомментирована специально:
-- запуск «как есть» с плейсхолдерами создал бы нерабочую задачу.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Шаг 1. Включить расширения (Database → Extensions тоже позволяет):
--   • pg_cron — планировщик внутри Postgres
--   • pg_net  — асинхронные HTTP-запросы из SQL (net.http_post / http_get)
-- ---------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pg_cron;
CREATE EXTENSION IF NOT EXISTS pg_net;

-- Расширения pg_cron/pg_net живут в схемах cron/net; для удобства проверок:
GRANT USAGE ON SCHEMA cron TO postgres;
GRANT USAGE ON SCHEMA net TO postgres;

-- ---------------------------------------------------------------------------
-- Шаг 2. Расписание: каждый час дёргать POST <APP_DOMAIN>/api/parse
--   (Vercel Cron использует '0 * * * *' — то же самое расписание здесь.)
--
-- ЗАМЕНИТЕ <APP_DOMAIN> и <CRON_SECRET>, затем раскомментируйте блок:
-- ---------------------------------------------------------------------------
-- SELECT cron.schedule(
--     'tgfeed-parse-hourly',            -- имя задачи (уникальное)
--     '0 * * * *',                      -- cron-выражение: ежечасно на 00-й минуте
--     $$
--     SELECT net.http_post(
--         url                := 'https://<APP_DOMAIN>/api/parse',
--         headers            := jsonb_build_object(
--                                'Content-Type',  'application/json',
--                                'Authorization', 'Bearer <CRON_SECRET>'
--                            ),
--         body               := '{}'::jsonb,
--         timeout_milliseconds := 30000
--     ) AS request_id;
--     $$
-- );
--
-- ВАЖНО: таргет — именно приложение на Vercel (<APP_DOMAIN>/api/parse),
-- НЕ <PROJECT_REF>.supabase.co: эндпоинт парсера живёт в Next.js.
-- Запрос идёт GET'ом/POST'ом из IP Supabase — он попадает под rate limit
-- парсера (20/мин/IP), ежечасный запуск укладывается с запасом.
--
-- Если приложение ещё ожидает POST с телом {"username": "..."} для одного
-- канала — пустой JSON '{}' запускает парсинг ВСЕХ активных каналов
-- (так же, как вызов без параметров в UI).
-- ---------------------------------------------------------------------------

